// The session shape and every legal mutation of it: the Kotlin port of src/core/session.js.
//
// A session is a JSON object, not a data class, for the same reason the JS keeps it plain:
// it round-trips through backups shared with the web app, it may carry fields a newer app
// wrote, and its key order is part of what the export and the canonical form see. Every
// reducer returns a NEW object with rev + 1, exactly as the JS does.
//
// Two invariants: nothing outside this file mutates a session, and no timestamp or
// randomness reaches anything the prompt builder reads. `now` and ids always come in.

typealias Session = JsonObject

const val SCHEMA = 2
const val MAX_SESSION_NAME = 120
const val MAX_TAGS = 12
const val MAX_TAG_LENGTH = 32
val REPORT_CATEGORIES = listOf("offensive", "harmful", "inaccurate", "other")
const val MAX_REPORT_NOTE = 2000

/** Coverage may rise at most one level per dimension per turn... */
private const val MAX_LEVEL_RISE_PER_TURN = 1
/** ...and at most this many dimensions may rise in any single turn. */
private const val MAX_DIMENSIONS_RISING_PER_TURN = 2

private fun recordArray(e: JsonElement?): List<JsonObject> =
    (e as? JsonArray)?.filterIsInstance<JsonObject>() ?: emptyList()

private fun items(e: JsonElement?): List<JsonElement> = (e as? JsonArray) ?: emptyList()

private fun nonEmpty(e: JsonElement?): Boolean = stringOf(e)?.let { jsTrim(it).isNotEmpty() } ?: false

private fun turnsOf(s: JsonObject): List<JsonElement> = items(s["turns"])

fun createSession(id: String?, now: JsonElement = num(0), device: JsonElement = str("desktop")): Session {
    if (id.isNullOrEmpty()) throw IllegalArgumentException("createSession requires an id (generated by the caller, not core)")
    return createSession(str(id), now, device)
}

private fun createSession(id: JsonElement, now: JsonElement, device: JsonElement): Session {
    val coverage = obj(DIMENSION_IDS.associateWith { _ ->
        obj(
            "level" to str("thin"), "status" to str("probing"), "gap" to JsonNull, "evidence" to JsonNull,
            "turnsSpent" to num(0), "lastTurn" to num(0), "waivedReason" to JsonNull,
        )
    })
    return obj(
        "schema" to num(SCHEMA),
        "id" to id,
        "rev" to num(0),
        "createdAt" to now,
        "updatedAt" to now,
        "status" to str("interviewing"),
        "name" to str(""),
        "title" to str(""),
        "tags" to arr(emptyList()),
        "archivedAt" to num(0),
        "opening" to str(""),
        "turns" to arr(emptyList()),
        "coverage" to coverage,
        "facts" to arr(emptyList()),
        "moveHistory" to arr(emptyList()),
        "openQuestions" to arr(emptyList()),
        "synthesis" to obj(
            "text" to str(""), "tier" to str(""), "at" to num(0), "stale" to bool(false),
            "assumptions" to arr(emptyList()),
        ),
        "draftAnswer" to str(""),
        "pending" to JsonNull,
        "zeroGainStreak" to num(0),
        "wrapOffered" to bool(false),
        "meta" to obj("device" to device),
    )
}

/** `{...session, ...patch, rev: rev + 1, updatedAt: now ?? updatedAt}`. Reducers always pass
 *  a value (JS defaults it to 0); only an explicit JS null keeps the old updatedAt. */
private fun bump(session: Session, patch: List<Pair<String, JsonElement?>>, now: JsonElement?): Session =
    session.spread(
        patch + listOf(
            "rev" to jsPlus(session["rev"], 1),
            "updatedAt" to (if (now == null || now is JsonNull) session["updatedAt"] else now),
        ),
    )

/** Record a question that has been put to the user. */
fun askQuestion(
    session: Session, question: JsonElement?, dimension: JsonElement?, move: JsonElement = JsonNull,
    chips: JsonElement = arr(emptyList()), bridge: JsonElement = JsonNull,
    source: JsonElement = str("model"), now: JsonElement = num(0),
): Session {
    if (!truthy(question)) throw IllegalArgumentException("askQuestion requires a question")
    val n = turnsOf(session).size + 1
    val turn = obj(
        "id" to str("t$n"), "n" to num(n), "dimension" to dimension, "question" to question,
        "bridge" to bridge, "move" to move, "chips" to chips,
        "questionSource" to source,
        "answer" to str(""), "answerSource" to JsonNull, "draftText" to JsonNull,
        "skipped" to bool(false), "askedAt" to now, "answeredAt" to num(0), "classification" to JsonNull,
    )
    val patch = mutableListOf<Pair<String, JsonElement?>>("turns" to arr(turnsOf(session) + turn))
    if (truthy(move)) patch += "moveHistory" to arr(items(session["moveHistory"]) + move!!)
    val coverage = session["coverage"] as? JsonObject
    val key = stringOf(dimension) ?: dimension?.let { jsString(it) }
    if (truthy(dimension) && key != null && coverage?.get(key) != null) {
        val cur = coverage.getValue(key) as? JsonObject ?: JsonObject(emptyMap())
        patch += "coverage" to coverage.spread(
            key to cur.spread("turnsSpent" to jsPlus(cur["turnsSpent"], 1), "lastTurn" to num(n)),
        )
    }
    return bump(session, patch, now)
}

/**
 * Record the user's answer to the open turn. Chip and unedited-draft answers are Claude's
 * words, not the user's, and must never take a dimension to `covered`.
 */
fun answerQuestion(
    session: Session, text: JsonElement?, source: JsonElement = str("typed"),
    classification: JsonElement = JsonNull, now: JsonElement = num(0),
): Session {
    val turns = turnsOf(session).toMutableList()
    val idx = turns.size - 1
    if (idx < 0) throw IllegalStateException("no open turn to answer")
    val open = turns[idx] as? JsonObject ?: JsonObject(emptyMap())
    var resolvedSource = source
    if (jsEq(source, "draft")) {
        val draft = open["draftText"]
        val unedited = draft != null && draft !is JsonNull && strictEquals(draft, text)
        resolvedSource = str(if (unedited) "draft-unedited" else "draft-edited")
    }
    turns[idx] = open.spread(
        "answer" to text, "answerSource" to resolvedSource, "answeredAt" to now, "classification" to classification,
    )
    val patch = mutableListOf<Pair<String, JsonElement?>>("turns" to arr(turns), "draftAnswer" to str(""))
    if (jsEq(open["n"], 1) && !truthy(session["opening"])) patch += "opening" to text
    return bump(session, patch, now)
}

private fun strictEquals(a: JsonElement?, b: JsonElement?): Boolean = when {
    a == null || b == null -> a == null && b == null
    a is JsonPrimitive && b is JsonPrimitive -> a.isString == b.isString && a.content == b.content
    else -> a === b
}

/**
 * The user declined to answer. `skipped` is structurally distinct from an answer reading
 * "(skipped)": openTurn, the transcript and the export all branch on the flag.
 */
fun skipQuestion(session: Session, now: JsonElement = num(0)): Session {
    val turns = turnsOf(session).toMutableList()
    val idx = turns.size - 1
    if (idx < 0) throw IllegalStateException("no open turn to skip")
    val last = turns[idx]
    if (truthy(last["answer"]) || truthy(last["skipped"])) throw IllegalStateException("no open turn to skip")
    turns[idx] = (last as JsonObject).spread(
        "skipped" to bool(true), "answeredAt" to now, "classification" to str("refusal"),
    )
    return bump(session, listOf("turns" to arr(turns), "draftAnswer" to str("")), now)
}

fun setDraftText(session: Session, text: JsonElement?, now: JsonElement = num(0)): Session {
    val turns = turnsOf(session).toMutableList()
    val idx = turns.size - 1
    if (idx < 0) return session
    turns[idx] = (turns[idx] as JsonObject).spread("draftText" to text)
    return bump(session, listOf("turns" to arr(turns), "draftAnswer" to text), now)
}

fun setDraftAnswer(session: Session, text: JsonElement?, now: JsonElement = num(0)): Session =
    bump(session, listOf("draftAnswer" to text), now)

/** Copy generated text only, never an export containing answers or older private reports. */
fun reportableOutput(session: Session, kind: String?, turnId: String? = null): JsonObject? {
    val turns = recordArray(session["turns"])
    if (kind == "result") {
        val parts = mutableListOf<String>()
        val synthesis = session["synthesis"]
        if (nonEmpty(synthesis["text"])) {
            if (nonEmpty(session["title"])) parts += stringOf(session["title"])!!
            parts += stringOf(synthesis["text"])!!
            parts += items(synthesis["assumptions"]).filter(::nonEmpty).map { stringOf(it)!! }
            for (q in recordArray(session["openQuestions"])) {
                if (nonEmpty(q["question"])) parts += stringOf(q["question"])!!
                if (nonEmpty(q["why_it_matters"])) parts += stringOf(q["why_it_matters"])!!
            }
        }
        for (turn in turns) {
            if (stringOf(turn["questionSource"]) == "model") {
                if (nonEmpty(turn["bridge"])) parts += stringOf(turn["bridge"])!!
                if (nonEmpty(turn["question"])) parts += stringOf(turn["question"])!!
            }
            parts += generatedSuggestions(turn)
        }
        if (parts.isNotEmpty()) for (id in DIMENSION_IDS) {
            if (nonEmpty(session["coverage"][id]["gap"])) parts += stringOf(session["coverage"][id]["gap"])!!
        }
        return if (parts.isEmpty()) null else obj(
            "kind" to str(kind), "turnId" to JsonNull, "question" to JsonNull, "text" to str(parts.joinToString("\n\n")),
        )
    }
    val turn = turns.firstOrNull { stringOf(it["id"]) == turnId } ?: return null
    if (!nonEmpty(turn["question"])) return null
    val text = when (kind) {
        "question" -> if (stringOf(turn["questionSource"]) == "model")
            listOfNotNull(turn["bridge"], turn["question"]).filter(::nonEmpty).joinToString("\n\n") { stringOf(it)!! } else ""
        "suggestions" -> generatedSuggestions(turn).joinToString("\n")
        else -> ""
    }
    return if (text.isEmpty()) null else obj(
        "kind" to str(kind!!), "turnId" to str(turnId!!), "question" to turn["question"], "text" to str(text),
    )
}

private fun generatedSuggestions(turn: JsonObject): List<String> {
    val texts = if (stringOf(turn["questionSource"]) == "model")
        items(turn["chips"]).filter(::nonEmpty).map { stringOf(it)!! }.toMutableList() else mutableListOf()
    if (isLowConfidence(turn) && nonEmpty(turn["answer"]) && stringOf(turn["answer"]) !in texts)
        texts += stringOf(turn["answer"])!!
    return texts
}

private fun reportId(id: JsonElement?): Boolean = stringOf(id)?.let {
    it.length in 1..128 && it.all { c -> c in 'a'..'z' || c in 'A'..'Z' || c in '0'..'9' || c == '_' || c == '-' }
} == true

private fun normalizeReport(raw: JsonElement?): JsonObject? {
    val report = raw as? JsonObject ?: return null
    val note = stringOf(report["note"]) ?: return null
    if (!reportId(report["id"]) || stringOf(report["category"]) !in REPORT_CATEGORIES || note.length > MAX_REPORT_NOTE
        || !isFiniteNumber(report["at"]) || toNumber(report["at"]) < 0 || toNumber(report["at"]) > 8.64e15) return null
    val output = report["output"] as? JsonObject ?: return null
    val text = stringOf(output["text"]) ?: return null
    if (!nonEmpty(output["text"]) || text.length > 262144) return null
    if (stringOf(output["kind"]) == "result") {
        if (output["turnId"] !is JsonNull || output["question"] !is JsonNull) return null
    } else if (stringOf(output["kind"]) !in setOf("question", "suggestions") || !reportId(output["turnId"])
        || !nonEmpty(output["question"]) || stringOf(output["question"])!!.length > 262144) return null
    return obj(
        "id" to report["id"], "at" to report["at"], "category" to report["category"], "note" to str(jsTrim(note)),
        "output" to obj("kind" to output["kind"], "turnId" to output["turnId"],
            "question" to output["question"], "text" to output["text"]),
    )
}

private fun reportsOf(session: Session): List<JsonObject> =
    recordArray(session["contentReports"]).mapNotNull(::normalizeReport).distinctBy { stringOf(it["id"]) }

/** Bind a report to the exact output shown, not whatever a delayed save now sees. */
fun addContentReport(
    session: Session, id: JsonElement?, output: JsonElement?, category: JsonElement?,
    note: JsonElement = str(""), now: JsonElement = num(0),
): Session {
    val report = normalizeReport(obj("id" to id, "output" to output, "category" to category, "note" to note, "at" to now))
        ?: throw IllegalArgumentException("Invalid content report category, note or output.")
    val reports = reportsOf(session)
    reports.firstOrNull { it["id"] == id }?.let { existing ->
        if (existing["category"] == report["category"] && existing["note"] == report["note"] && existing["output"] == report["output"])
            return session
        throw IllegalArgumentException("This report id already belongs to another report.")
    }
    val snapshot = report["output"] as JsonObject
    val current = reportableOutput(session, stringOf(snapshot["kind"]), stringOf(snapshot["turnId"]))
    if (current != snapshot) throw IllegalStateException("The reported output changed. Reopen Report for that output.")
    return bump(session, listOf("contentReports" to arr(reports + report)), now)
}

/** A settled turn/draft may have begun before a report became durable. */
fun mergeContentReports(session: Session, latest: Session?, now: JsonElement = num(0)): Session {
    val reports = linkedMapOf<String, JsonObject>()
    for (report in reportsOf(session) + reportsOf(latest ?: obj())) reports[stringOf(report["id"])!!] = report
    val merged = arr(reports.values.toList())
    if (reports.isEmpty() || merged == session["contentReports"]) return session
    return bump(session, listOf("contentReports" to merged), now)
}

/** Same turn and dimension, with no new answer or second coverage judgement. */
fun replaceReportedQuestion(session: Session, reportId: String?, now: JsonElement = num(0)): Session {
    val open = openTurn(session)
    val report = reportsOf(session).firstOrNull { stringOf(it["id"]) == reportId }
    if (stringOf(session["status"]) != "interviewing" || truthy(session["pending"]) || open == null || report == null
        || stringOf(report["output"]["kind"]) !in setOf("question", "suggestions")
        || stringOf(open["questionSource"]) != "model" || open["id"] != report["output"]["turnId"]
        || open["question"] != report["output"]["question"]) {
        throw IllegalStateException("Only the reported current unanswered question can be replaced.")
    }
    val asked = turnsOf(session).mapNotNull { stringOf(it["question"]) }.toMutableSet()
    for (r in reportsOf(session)) stringOf(r["output"]["question"])?.let(asked::add)
    val dimension = stringOf(open["dimension"])
    val question = dimension?.let { getDimension(it)["bank"] as? JsonArray }
        ?.mapNotNull(::stringOf)?.firstOrNull { it !in asked }
        ?: throw IllegalStateException("No different checklist question is available for this dimension.")
    val turns = turnsOf(session).toMutableList()
    turns[turns.lastIndex] = open.spread(
        "question" to str(question), "bridge" to JsonNull, "chips" to arr(emptyList()), "move" to JsonNull,
        "questionSource" to str("replacement"), "askedAt" to now,
    )
    return bump(session, listOf("turns" to arr(turns)), now)
}

/** True when this answer's provenance means it cannot support a `covered` grade. */
fun isLowConfidence(turn: JsonElement?): Boolean =
    jsEq(turn["answerSource"], "chip") || jsEq(turn["answerSource"], "draft-unedited")

/**
 * Apply a parsed turn result, clamping the model's coverage claims. Self-reported coverage
 * drifts optimistic, and this ratchet is the structural defence: coverage never falls,
 * never leaps more than one level, and never more than two dimensions at a time. Loosening
 * any of it makes the interview stop early and produce a useless prompt.
 */
fun applyCoverage(
    session: Session, claimed: JsonElement?, lowConfidenceDimension: JsonElement = JsonNull,
    cappedDimensions: JsonElement = arr(emptyList()), now: JsonElement = num(0),
): Session {
    val coverage = session["coverage"] as JsonObject
    val next = LinkedHashMap<String, JsonElement>()
    val risen = mutableListOf<String>()
    val capped = items(cappedDimensions).mapNotNull { stringOf(it) }.toSet()

    for (id in DIMENSION_IDS) {
        val cur = coverage[id] as JsonObject
        val claim = if (truthy(claimed)) claimed[id] else null
        if (!truthy(claim) || !jsEq(cur["status"], "probing")) { next[id] = cur; continue }

        var level = stringOf(claim["level"])?.takeIf { it in LEVELS } ?: stringOf(cur["level"])!!

        // Provenance and dodge caps: never better than `partial`.
        if ((jsEq(lowConfidenceDimension, id) || id in capped) && level == "covered") level = "partial"
        // Evidence requirement: `covered` without a user quote is not covered.
        if (level == "covered" && !nonEmpty(claim["evidence"])) level = "partial"

        // Ratchet: never decrease, never rise more than one level.
        val curRank = LEVEL_RANK.getValue(stringOf(cur["level"])!!)
        if (LEVEL_RANK.getValue(level) < curRank) level = stringOf(cur["level"])!!
        if (LEVEL_RANK.getValue(level) - curRank > MAX_LEVEL_RISE_PER_TURN) {
            level = LEVELS[(curRank + MAX_LEVEL_RISE_PER_TURN).coerceIn(0, 2)]
        }
        if (LEVEL_RANK.getValue(level) > curRank) risen += id

        next[id] = cur.spread(
            "level" to str(level),
            "gap" to if (level == "covered") JsonNull else if (nonEmpty(claim["gap"])) claim["gap"] else cur["gap"],
            "evidence" to if (level == "covered") claim["evidence"] else cur["evidence"],
        )
    }

    // Cap the number of dimensions allowed to rise: keep the most defensible.
    if (risen.size > MAX_DIMENSIONS_RISING_PER_TURN) {
        val keep = risen.take(MAX_DIMENSIONS_RISING_PER_TURN).toSet()
        for (id in risen) {
            if (id !in keep) next[id] = (next.getValue(id) as JsonObject).spread("level" to (coverage[id] as JsonObject)["level"])
        }
    }
    return bump(session, listOf("coverage" to JsonObject(next)), now)
}

fun normalizeSessionName(value: JsonElement?): String =
    stringOf(value)?.let { jsSlice(collapseJsSpace(jsTrim(it)), MAX_SESSION_NAME) } ?: ""

fun normalizeTags(value: JsonElement?): List<String> {
    if (value !is JsonArray) return emptyList()
    val tags = mutableListOf<String>()
    val seen = mutableSetOf<String>()
    for (raw in value) {
        val s = stringOf(raw) ?: continue
        val tag = jsSlice(collapseJsSpace(jsTrim(s)), MAX_TAG_LENGTH)
        val key = jsLower(tag)
        if (tag.isEmpty() || key in seen) continue
        seen += key
        tags += tag
        if (tags.size >= MAX_TAGS) break
    }
    return tags
}

fun sessionDisplayTitle(session: JsonElement?, fallback: String = "Untitled idea"): String =
    normalizeSessionName(session["name"]).ifEmpty { null }
        ?: normalizeSessionName(session["title"]).ifEmpty { null }
        ?: normalizeSessionName(session["opening"]).ifEmpty { null }
        ?: fallback

private fun normalizeFact(e: JsonElement?): String =
    jsTrim(collapseJsSpace(jsLower(jsString(e)).filter { it in 'a'..'z' || it in '0'..'9' || it == ' ' }))

/** Merge new facts into the ledger, skipping near-duplicates. */
fun addFacts(session: Session, facts: JsonElement?, now: JsonElement = num(0)): Session {
    if (facts !is JsonArray || facts.isEmpty()) return session
    val seen = items(session["facts"]).map { normalizeFact(it["fact"]) }.toMutableSet()
    val added = mutableListOf<JsonElement>()
    for (f in facts) {
        if (!truthy(f) || !nonEmpty(f["fact"])) continue
        val key = normalizeFact(f["fact"])
        if (key in seen) continue
        seen += key
        added += obj(
            "dimension" to (if (truthy(f["dimension"])) f["dimension"] else JsonNull),
            "fact" to str(jsTrim(stringOf(f["fact"])!!)),
        )
    }
    if (added.isEmpty()) return session
    return bump(session, listOf("facts" to arr(items(session["facts"]) + added)), now)
}

/** The user told us to stop asking about this. Permanent, with an undo. */
fun waiveDimension(session: Session, id: String?, reason: JsonElement = JsonNull, now: JsonElement = num(0)) =
    setStatus(session, id, "waived", listOf("waivedReason" to reason), now)

/** The user genuinely cannot know this yet. Stops counting against readiness. */
fun deferDimension(session: Session, id: String?, now: JsonElement = num(0)) =
    setStatus(session, id, "deferred", emptyList(), now)

fun resumeDimension(session: Session, id: String?, now: JsonElement = num(0)) =
    setStatus(session, id, "probing", listOf("waivedReason" to JsonNull), now)

private fun setStatus(
    session: Session, id: String?, status: String, extra: List<Pair<String, JsonElement?>>, now: JsonElement?,
): Session {
    getDimension(id)
    val coverage = session["coverage"] as JsonObject
    val cur = coverage[id!!] as? JsonObject ?: JsonObject(emptyMap())
    return bump(session, listOf("coverage" to coverage.spread(id to cur.spread(listOf("status" to str(status)) + extra))), now)
}

fun setPending(session: Session, pending: JsonElement?, now: JsonElement = num(0)) = bump(session, listOf("pending" to pending), now)
fun clearPending(session: Session, now: JsonElement = num(0)) = bump(session, listOf("pending" to JsonNull), now)
fun setZeroGainStreak(session: Session, n: Int, now: JsonElement = num(0)) = bump(session, listOf("zeroGainStreak" to num(n)), now)
fun setWrapOffered(session: Session, v: Boolean, now: JsonElement = num(0)) = bump(session, listOf("wrapOffered" to bool(v)), now)
fun setTitle(session: Session, title: JsonElement?, now: JsonElement = num(0)) = bump(session, listOf("title" to title), now)
fun setStatusField(session: Session, status: String, now: JsonElement = num(0)) = bump(session, listOf("status" to str(status)), now)
fun renameSession(session: Session, name: JsonElement?, now: JsonElement = num(0)) =
    bump(session, listOf("name" to str(normalizeSessionName(name))), now)
fun setSessionTags(session: Session, tags: JsonElement?, now: JsonElement = num(0)) =
    bump(session, listOf("tags" to arr(normalizeTags(tags).map(::str))), now)

fun archiveSession(session: Session, now: JsonElement = num(0)): Session {
    val at = when {
        truthy(now) -> now
        truthy(session["updatedAt"]) -> session["updatedAt"]
        else -> num(1)
    }
    return bump(session, listOf("archivedAt" to at), now)
}

fun restoreSession(session: Session, now: JsonElement = num(0)) = bump(session, listOf("archivedAt" to num(0)), now)

fun copySession(session: Session, id: JsonElement?, name: JsonElement = JsonNull, now: JsonElement = num(0)): Session {
    if (!truthy(id)) throw IllegalArgumentException("copySession requires a new id")
    val chosen = if (name == null || name is JsonNull) session["name"] else name
    return bump(session, listOf("id" to id, "name" to str(normalizeSessionName(chosen))), now)
}

fun setSynthesis(
    session: Session, text: JsonElement?, tier: JsonElement = str(""), assumptions: JsonElement = arr(emptyList()),
    openQuestions: JsonElement = JsonNull, now: JsonElement = num(0),
): Session {
    val patch = mutableListOf<Pair<String, JsonElement?>>(
        "synthesis" to obj("text" to text, "tier" to tier, "at" to now, "stale" to bool(false), "assumptions" to assumptions),
        "status" to str("done"),
    )
    if (truthy(openQuestions)) patch += "openQuestions" to openQuestions
    return bump(session, patch, now)
}

/** Re-entry: a finished session that gains a turn has a stale synthesis. */
fun reopen(session: Session, now: JsonElement = num(0)): Session = bump(
    session,
    listOf(
        "status" to str("interviewing"),
        "synthesis" to ((session["synthesis"] as? JsonObject) ?: JsonObject(emptyMap())).spread("stale" to bool(true)),
        "wrapOffered" to bool(false),
    ),
    now,
)

/** Forward-migrate a stored session. Unknown future schemas are rejected, not guessed at. */
fun migrate(stored: JsonElement?): Session? {
    if (!isRecord(stored)) return null
    stored as JsonObject
    if (jsGreater(stored["schema"], SCHEMA.toDouble())) return null
    val base = createSession(
        if (truthy(stored["id"])) stored["id"]!! else str("recovered"),
        if (truthy(stored["createdAt"])) stored["createdAt"]!! else num(0),
        str("desktop"),
    )
    val merged = LinkedHashMap<String, JsonElement?>(base.spread(stored).spread("schema" to num(SCHEMA)))
    merged["name"] = str(normalizeSessionName(stored["name"]))
    merged["tags"] = arr(normalizeTags(stored["tags"]).map(::str))
    val archivedAt = stored["archivedAt"]
    merged["archivedAt"] = if (isFiniteNumber(archivedAt) && toNumber(archivedAt) > 0) archivedAt else num(0)
    merged["turns"] = arr(recordArray(stored["turns"]).map { turn ->
        turn.spread("chips" to arr((turn["chips"] as? JsonArray)?.filter(::isString) ?: emptyList()))
    })
    if (stored.containsKey("contentReports")) merged["contentReports"] = arr(reportsOf(stored))
    merged["facts"] = arr(recordArray(stored["facts"]))
    merged["moveHistory"] = arr((stored["moveHistory"] as? JsonArray)?.filter(::isString) ?: emptyList())
    merged["openQuestions"] = arr(recordArray(stored["openQuestions"]))
    merged["pending"] = if (isRecord(stored["pending"])) stored["pending"] else JsonNull
    val baseCoverage = base["coverage"] as JsonObject
    val coverage = LinkedHashMap<String, JsonElement>(baseCoverage)
    for (id in DIMENSION_IDS) {
        val c = stored["coverage"]
        if (isRecord(c) && isRecord(c[id])) {
            var entry = (baseCoverage[id] as JsonObject).spread(c[id] as JsonObject)
            // An unknown level or status disables the ratchet (see session.js); reset it.
            if (stringOf(entry["level"]) !in LEVELS) entry = entry.spread("level" to str("thin"))
            if (stringOf(entry["status"]) !in STATUSES) entry = entry.spread("status" to str("probing"))
            if (!isFiniteNumber(entry["turnsSpent"])) entry = entry.spread("turnsSpent" to num(0))
            coverage[id] = entry
        }
    }
    merged["coverage"] = JsonObject(coverage)
    val synthesis = stored["synthesis"] as? JsonObject ?: JsonObject(emptyMap())
    merged["synthesis"] = (base["synthesis"] as JsonObject).spread(synthesis).spread(
        "assumptions" to arr((synthesis["assumptions"] as? JsonArray)?.filter(::isString) ?: emptyList()),
    )
    merged["meta"] = (base["meta"] as JsonObject).spread(stored["meta"] as? JsonObject ?: JsonObject(emptyMap()))
    return obj(merged)
}

/** The open turn, if one is awaiting an answer. */
fun openTurn(session: Session): JsonObject? {
    val last = turnsOf(session).lastOrNull() as? JsonObject ?: return null
    return if (!truthy(last["answer"]) && !truthy(last["skipped"])) last else null
}

fun answeredTurns(session: Session): List<JsonObject> =
    turnsOf(session).filterIsInstance<JsonObject>().filter { truthy(it["answer"]) || truthy(it["skipped"]) }
